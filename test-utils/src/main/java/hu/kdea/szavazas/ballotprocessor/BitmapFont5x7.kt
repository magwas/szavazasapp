    /**
     * Draws a string on an RGB [Planar] image using the built-in 5x7 font.
     *
     * @param image RGB Planar<GrayU8> (3 bands). The image is modified in place.
     * @param text The string to render (only printable ASCII 32..126 are drawn).
     * @param x X coordinate of the top-left corner.
     * @param y Y coordinate of the top-left corner.
     * @param color ARGB color (alpha ignored). Background is not drawn.
     * @param fontSize Ignored for this fixed-size font; kept for API compatibility.
     */
    fun drawString(
        image: Planar<GrayU8>,
        text: String,
        x: Int,
        y: Int,
        color: Int,
        fontSize: Float = 12f
    ) {
        val r = (color shr 16) and 0xFF
        val g = (color shr 8) and 0xFF
        val b = color and 0xFF
        val bandR = image.getBand(0)
        val bandG = image.getBand(1)
        val bandB = image.getBand(2)
        var cursorX = x

        for (ch in text) {
            if (ch.code < 32 || ch.code > 126) continue
            val glyphIdx = (ch.code - 32) * 5
            for (col in 0 until 5) {
                val line = font[glyphIdx + col]
                for (row in 0 until 7) {
                    if ((line and (1 shl row)) != 0) {
                        val px = cursorX + col
                        val py = y + row
                        if (px in 0 until image.width && py in 0 until image.height) {
                            bandR.set(px, py, r)
                            bandG.set(px, py, g)
                            bandB.set(px, py, b)
                        }
                    }
                }
            }
            cursorX += 6 // char width + 1px spacing
        }
    }
